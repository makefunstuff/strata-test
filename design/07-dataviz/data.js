/* The Harrow Estuary: 31 years of spring-tide maxima, 12 gauges, one datum change.
   All numbers are synthetic and generated from a fixed seed — this is a design
   exercise, and a chart of invented data must say so in the file, not in a footnote. */
const lcg = (seed) => { let s = seed >>> 0; return () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296); };
const gauss = (r) => { const u = Math.max(r(), 1e-9), v = r(); return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v); };
const round = (v, d = 2) => +v.toFixed(d);

export const META = {
  place: "Harrow Estuary",
  datum: "CD (chart datum) — the 1994–2010 series is referenced to OD -1.9 m",
  source: "Harrow Estuary Authority, gauge network (synthetic, seeded)",
  generated: "generated by data.js from seed 4122",
};

/* 01 · the claim: highest spring tide each year, 1994-2024, in metres above CD */
export const springs = (() => {
  const r = lcg(4122);
  const out = [];
  for (let year = 1994; year <= 2024; year++) {
    const t = year - 1994;
    const base = 4.02 + 0.031 * t + 0.9 * Math.sin(t / 5.3) * 0.22;
    const spike = r() < 0.26 ? 0.34 + r() * 0.3 : 0;
    const v = base + gauss(r) * 0.14 + spike;
    out.push({ year, level: round(Math.max(3.4, v), 2), spike: spike > 0 });
  }
  // 2011: the datum change. The gauges moved to CD; the recorded series steps.
  for (const p of out) if (p.year >= 2011) { p.level = round(p.level - 0.28, 2); p.datum = "CD"; }
  else p.datum = "OD";
  return out;
})();

const fit = (rows) => {
  const n = rows.length;
  const xs = rows.map((p) => p.year - 1994);
  const ys = rows.map((p) => p.level);
  const mx = xs.reduce((a, b) => a + b) / n, my = ys.reduce((a, b) => a + b) / n;
  const b = xs.reduce((a, x, i) => a + (x - mx) * (ys[i] - my), 0) / xs.reduce((a, x) => a + (x - mx) ** 2, 0);
  const a = my - b * mx;
  return { a: round(a, 3), b: round(b, 4), from: rows[0].year, to: rows[n - 1].year, n,
    rise: round(ys[n - 1] - ys[0], 2) };
};

/* the fit on the CD segment — the only part of the record with one datum */
export const trend = fit(springs.filter((p) => p.datum === "CD"));
/* the fit across the datum change, kept as the mistake the page warns about */
export const fitAcrossDatum = fit(springs);
export const stormYears = springs.filter((p) => p.spike).length;
export const peakYear = springs.reduce((m, p) => (p.level > m.level ? p : m), springs[0]);

/* 02 · twelve gauges, 60 days of daily maximum water level (a season, one flood) */
export const GAUGES = ["Harrow Mouth", "Clinkham", "Salt Pits", "Red Rock", "Grout Water",
  "Alder Reach", "Stase's Quay", "Mudmere", "Tidcombe", "Wearling", "Ferry Bank", "Upper Harrow"];
export const season = (() => {
  const r = lcg(771);
  const days = 60;                                   // 1 Nov – 31 Dec
  const start = new Date(Date.UTC(2024, 10, 1));
  const flood = 26;                                  // the storm surge day
  return GAUGES.map((name, gi) => {
    const upstream = gi / (GAUGES.length - 1);       // 0 at the mouth, 1 at the top
    const base = 1.15 - 0.55 * upstream + gauss(r) * 0.06;
    const lag = Math.round(1.5 + upstream * 5);      // the surge travels up the estuary
    const series = [];
    for (let d = 0; d < days; d++) {
      const spring = 0.42 * Math.sin(((d + gi * 0.7) / 12.42) * 2 * Math.PI);
      const trendUp = 0.0042 * d;
      const surge = d >= flood + lag
        ? (2.5 - 0.9 * upstream) * Math.exp(-(d - flood - lag) / 5.5)
        : 0;
      const v = base + spring + trendUp + surge + gauss(r) * 0.05;
      // two inland gauges went dark after a storm damage notice: the record has a hole,
      // and the design must show the hole rather than invent a line across it
      const dark = (gi === 2 || gi === 7) && d >= 12 && d < 53;
      series.push({
        date: new Date(start.getTime() + d * 864e5).toISOString().slice(0, 10),
        level: dark ? null : round(Math.max(0, v), 2),
      });
    }
    const peak = series.reduce((m, p) => (p.level != null && (m === null || p.level > m.level) ? p : m), null);
    return { name, code: ["HM", "CL", "SP", "RR", "GW", "AR", "SQ", "MM", "TC", "WL", "FB", "UH"][gi], series, peak, upstream: round(upstream, 2) };
  });
})();

export const FLOOD_LINE = 2.2;   // the flood line, metres above CD, at the mouth

/* 03 · distribution of daily maxima by month, 2024 */
export const months = (() => {
  const r = lcg(3301);
  const names = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
  return names.map((name, i) => {
    const centre = 1.2 + 0.5 * Math.max(0, Math.sin(((i - 1) / 12) * 2 * Math.PI)) + 0.34 * (i >= 10 ? 1 : 0);
    const spread = 0.28 + 0.16 * (i >= 9 ? 1 : 0);
    const pts = Array.from({ length: 30 }, () => centre + gauss(r) * spread + (r() < 0.09 ? spread * (1.6 + r()) : 0));
    const s = pts.slice().sort((a, b) => a - b);
    const q = (p) => round(s[Math.min(s.length - 1, Math.floor(p * (s.length - 1)))], 2);
    const lo = round(Math.max(s[0], q(0.05)), 2), hi = round(Math.min(s[s.length - 1], q(0.95) + spread), 2);
    return { name, n: pts.length, lo, q1: q(0.25), med: q(0.5), q3: q(0.75), hi, min: round(s[0], 2), max: round(s[s.length - 1], 2), points: pts.map((v) => round(v, 2)) };
  });
})();

/* 04 · hours above CD bands per month — additive, so a stack is honest */
export const bands = { keys: ["0.0-0.5", "0.5-1.0", "1.0-1.5", "1.5+"], colours: ["b1", "b2", "b3", "b4"] };
export const stacked = (() => {
  const r = lcg(909);
  const names = months.map((m) => m.name);
  return names.map((name, i) => {
    const winter = Math.max(0, Math.sin(((i - 0.5) / 12) * 2 * Math.PI));
    const tide = 0.6 + 0.4 * Math.abs(Math.sin(((i + 2) / 12) * 2 * Math.PI));
    const v = [
      Math.round(280 + 90 * tide + gauss(r) * 18),
      Math.round(150 + 120 * tide + gauss(r) * 14),
      Math.round(52 + 96 * winter + gauss(r) * 9),
      Math.round(6 + 78 * winter + gauss(r) * 5),
    ].map((x) => Math.max(0, x));
    return { name, values: v, total: v.reduce((a, b) => a + b, 0) };
  });
})();

/* 05 · then and now: the 1-in-50-year level for nine places, 1994 and 2024 */
export const towns = (() => {
  const r = lcg(5511);
  const rows = [
    ["Harrow Town", 0.92], ["Stase's Quay", 0.81], ["Tidcombe", 0.74], ["Mudmere", 0.66],
    ["Wearling", 0.58], ["Alder Reach", 0.47], ["Salt Pits", 0.39], ["Red Rock", 0.28], ["Clinkham", 0.18],
  ];
  return rows.map(([name, rise]) => {
    const then = round(2.6 + gauss(r) * 0.18 + rise * 0.4, 2);
    const now = round(then + rise, 2);
    return { name, then, now, rise: round(now - then, 2), pop: Math.round(900 + r() * 11000) };
  }).sort((a, b) => b.rise - a.rise);
})();

/* 06 · a year of days: 53 weeks × 7, the day's maximum above the flood line */
export const calendar = (() => {
  const r = lcg(1212);
  const start = new Date(Date.UTC(2024, 0, 1));
  const out = [];
  for (let d = 0; d < 366; d++) {
    const t = d / 366;
    const winter = Math.max(0, Math.cos(t * 2 * Math.PI) * 0.9 + 0.1);
    const springCycle = 0.55 * Math.abs(Math.sin((d / 12.42) * Math.PI));
    const v = 1.02 + 1.55 * winter * springCycle + gauss(r) * 0.26 + (d > 300 ? 0.22 : 0);
    out.push({ date: new Date(start.getTime() + d * 864e5).toISOString().slice(0, 10), level: round(Math.max(0, v), 2) });
  }
  return out;
})();

export const calStats = (() => {
  const v = calendar.map((d) => d.level).sort((a, b) => a - b);
  const over = calendar.filter((d) => d.level >= FLOOD_LINE);
  const q = (p) => v[Math.floor(p * (v.length - 1))];
  return {
    n: calendar.length, max: v[v.length - 1], med: round(q(0.5), 2),
    over: over.length, overDays: over.slice(0, 4).map((d) => d.date), maxDay: calendar.reduce((m, p) => (p.level > m.level ? p : m), calendar[0]),
    byMonth: Array.from({ length: 12 }, (_, m) => ({
      name: months[m].name,
      n: calendar.filter((d) => new Date(d.date).getUTCMonth() === m).length,
      over: calendar.filter((d) => new Date(d.date).getUTCMonth() === m && d.level >= FLOOD_LINE).length,
    })),
  };
})();

