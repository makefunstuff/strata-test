// Summarize results/<label>.jsonl into results/summary.md: accuracy by position, TTFT and total time, per question.
//   node scripts/report.ts [label ...]          default: every results/*.jsonl
// Regrades every row from its stored reply, so a grader change applies to old runs.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { grade, HERE, loadQuestions, packed, placeQuestions } from "./lib.ts";

const RES = join(HERE, "results");
const labels = process.argv.slice(2).length ? process.argv.slice(2)
  : readdirSync(RES).filter((f) => f.endsWith(".jsonl")).map((f) => f.slice(0, -6)).sort();
const qs = new Map(loadQuestions().map((q) => [q.id, q]));
const POS = ["start", "middle", "end"] as const;
const { corpus, files } = packed();
const placed = new Map(placeQuestions(corpus, files).map((q) => [q.id, q.position]));

const median = (xs: number[]) => {
  const s = xs.filter((x) => Number.isFinite(x)).sort((a, b) => a - b);
  if (!s.length) return NaN;
  return s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2;
};
const mean = (xs: number[]) => xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : NaN;
const f1 = (x: number) => (Number.isFinite(x) ? x.toFixed(1) : "–");
const frac = (rows: any[], key: string) => `${rows.filter((r) => r[key]).length}/${rows.length}`;

const runs = labels.map((label) => {
  const rows = readFileSync(join(RES, `${label}.jsonl`), "utf8").split("\n").filter(Boolean).map((l) => {
    const r = JSON.parse(l);
    const q = qs.get(r.id);
    return q ? { ...r, ...grade(q, r.reply ?? "") } : r;
  });
  const metaFile = join(RES, `${label}.meta.json`);
  const meta = existsSync(metaFile) ? JSON.parse(readFileSync(metaFile, "utf8")) : {};
  return { label, rows, meta };
});

let md = "# Results\n\nGenerated by `node scripts/report.ts` from `results/*.jsonl`.\n\n";
md += "## Accuracy by position (right = citation and answer both right)\n\n";
md += "| run | model | prompt tokens | truncated | start | middle | end | all | citation right | answer right |\n|---|---|---|---|---|---|---|---|---|---|\n";
for (const { label, rows, meta } of runs) {
  const by = (p: string) => rows.filter((r) => r.position === p);
  md += `| ${label} | ${meta.model ?? "?"} | ${median(rows.map((r) => r.prompt_tokens))} | ${meta.truncated_files?.length ? meta.truncated_files.length + " files" : "none"} | ` +
    POS.map((p) => frac(by(p), "correct")).join(" | ") + ` | **${frac(rows, "correct")}** | ${frac(rows, "cite_ok")} | ${frac(rows, "answer_ok")} |\n`;
}
md += "\n## Time per question (seconds)\n\n";
md += "| run | TTFT median | TTFT min–max | total median | total mean | total max | output tokens median | prefill tok/s median |\n|---|---|---|---|---|---|---|---|\n";
for (const { label, rows } of runs) {
  const ttft = rows.map((r) => r.ttft_s), tot = rows.map((r) => r.total_s);
  md += `| ${label} | ${f1(median(ttft))} | ${f1(Math.min(...ttft))}–${f1(Math.max(...ttft))} | ${f1(median(tot))} | ${f1(mean(tot))} | ${f1(Math.max(...tot))} | ` +
    `${median(rows.map((r) => r.completion_tokens))} | ${f1(median(rows.map((r) => r.prompt_tokens / r.ttft_s)))} |\n`;
}
for (const p of POS) {
  md += `\n### ${p}: TTFT / total median\n\n`;
  for (const { label, rows } of runs) {
    const b = rows.filter((r) => r.position === p);
    md += `- ${label}: ${f1(median(b.map((r) => r.ttft_s)))} s / ${f1(median(b.map((r) => r.total_s)))} s\n`;
  }
}
md += "\n## Per question\n\nEach cell: verdict, cited location, TTFT / total seconds. R = right, C = citation only, A = answer only, W = wrong.\n\n";
md += `| question | position | expected | ${runs.map((r) => r.label).join(" | ")} |\n|---|---|---|${runs.map(() => "---").join("|")}|\n`;
for (const q of loadQuestions()) {
  const cells = runs.map(({ rows }) => {
    const r = rows.find((x) => x.id === q.id);
    if (!r) return "–";
    const v = r.correct ? "R" : r.cite_ok ? "C" : r.answer_ok ? "A" : "W";
    return `${v} \`${r.citation ?? "none"}\` ${f1(r.ttft_s)}/${f1(r.total_s)}${r.error ? " (error)" : ""}`;
  });
  const pos = placed.get(q.id) ?? "?"
  md += `| ${q.id} | ${pos} | \`${q.paths[0]}:${q.line}\` | ${cells.join(" | ")} |\n`;
}
md += "\n## Misses\n\n";
for (const { label, rows } of runs) {
  for (const r of rows.filter((x) => !x.correct)) {
    md += `- **${label} / ${r.id}**: answer ${JSON.stringify(r.answer ?? r.reply?.slice(0, 200))}, cited \`${r.citation ?? "none"}\`` +
      (r.cited_text != null ? ` (${JSON.stringify(r.cited_text.trim().slice(0, 100))})` : "") + `${r.error ? `, error ${r.error}` : ""}\n`;
  }
}
writeFileSync(join(RES, "summary.md"), md);
console.log(md);
